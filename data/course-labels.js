window.IBC360_LABEL_HELPERS = {
  get(course) {
    const official = course?.nome_curso || "";
    const info = window.IBC360_COURSE_LABELS?.[official] || {};
    return {
      official,
      public_title: info.public_title || official,
      subtitle: info.subtitle || course?.resumo_aluno || "",
      status: info.status || "",
      badge: info.badge || "",
      edition_note: info.edition_note || "",
      exclusive: Boolean(info.exclusive),
      exclusive_badge: info.exclusive_badge || ""
    };
  },
  badge(info) {
    const parts = [];
    if (info?.badge) {
      const cls = info.status === "updated" ? "updated" : "new";
      parts.push(`<span class="course-version-badge ${cls}">${info.badge}</span>`);
    }
    if (info?.exclusive_badge) {
      parts.push(`<span class="course-version-badge exclusive">${info.exclusive_badge}</span>`);
    }
    return parts.join("");
  }
};
